#!/bin/sh
# Writes the values of plugin/models.conf into the agent files of both tools:
# - Claude Code: the model and effort lines of each plugin/agents/<agent>.md.
# - opencode: each opencode/agents/<agent>.md, generated whole from the
#   description and the body of plugin/agents/<agent>.md.
# Usage: sh scripts/set-models.sh [--check] [repository root]
# With --check it changes nothing and exits 1 when an agent file differs from
# the configuration. Exits 0 otherwise.
set -u

check=0
if [ "${1:-}" = "--check" ]; then
  check=1
  shift
fi
root=${1:-$(cd "$(dirname "$0")/.." && pwd)}
conf="$root/plugin/models.conf"
agents="$root/plugin/agents"
opencode_agents="$root/opencode/agents"

failures=0
fail() {
  printf 'FAIL %s\n' "$1"
  failures=$((failures + 1))
}

# Prints the value of a front matter key of an agent file.
field() {
  awk -v key="$2" 'NR == 1 { if ($0 != "---") exit; next }
                   $0 == "---" { exit }
                   index($0, key ": ") == 1 { print substr($0, length(key) + 3) }' "$1"
}

# Rewrites the model and effort lines of an agent file.
write_file() {
  tmp=$(mktemp) || return 1
  awk -v model="$2" -v effort="$3" '
    NR == 1 && $0 == "---" { inside = 1; print; next }
    inside && $0 == "---" { print "model: " model; print "effort: " effort; inside = 0; print; next }
    inside && (index($0, "model: ") == 1 || index($0, "effort: ") == 1) { next }
    { print }' "$1" > "$tmp" && cat "$tmp" > "$1"
  status=$?
  rm -f "$tmp"
  return $status
}

# Prints the opencode agent file made from a Claude Code agent file.
# opencode_file <agent name> <source file> <provider/model> <variant>
# An agent whose tools line has neither Edit nor Write may not edit files.
opencode_file() {
  printf -- '---\n'
  printf '# Generated by scripts/set-models.sh from plugin/agents/%s.md. Do not edit.\n' "$1"
  printf 'description: %s\n' "$(field "$2" description)"
  printf 'mode: subagent\n'
  printf 'model: %s#%s\n' "$3" "$4"
  tools=$(field "$2" tools)
  case $tools in
    ''|*Edit*|*Write*) ;;
    *) printf 'permissions:\n  - action: edit\n    resource: "*"\n    effect: deny\n' ;;
  esac
  printf -- '---\n'
  awk 'NR == 1 && $0 == "---" { inside = 1; next }
       inside && $0 == "---" { inside = 0; next }
       !inside { print }' "$2"
}

if [ ! -f "$conf" ]; then
  fail "$conf is missing"
  exit 1
fi

configured=" "
while read -r agent model effort omodel ovariant extra; do
  case $agent in ''|'#'*) continue ;; esac
  file="$agents/$agent.md"
  configured="$configured$agent "

  case $model in
    haiku|sonnet|opus|fable|inherit|claude-*) ;;
    *) fail "models.conf: model '$model' of $agent is not haiku, sonnet, opus, fable, inherit, or a claude- id"; continue ;;
  esac
  case $effort in
    low|medium|high|xhigh|max) ;;
    *) fail "models.conf: effort '$effort' of $agent is not low, medium, high, xhigh, or max"; continue ;;
  esac
  case $omodel in
    *'#'*|/*|*/) omodel_ok=0 ;;
    */*) omodel_ok=1 ;;
    *) omodel_ok=0 ;;
  esac
  if [ "$omodel_ok" -eq 0 ]; then
    fail "models.conf: opencode model '$omodel' of $agent is not provider/model"
    continue
  fi
  case $ovariant in
    ''|*[!a-z0-9-]*) fail "models.conf: opencode variant '$ovariant' of $agent is not a word of lowercase letters, digits, and hyphens"; continue ;;
  esac
  if [ -n "$extra" ]; then
    fail "models.conf: the line of $agent has more than five fields"
    continue
  fi
  if [ ! -f "$file" ]; then
    fail "plugin/agents/$agent.md is missing, but models.conf configures $agent"
    continue
  fi

  if [ "$check" -eq 1 ]; then
    [ "$(field "$file" model)" = "$model" ] ||
      fail "plugin/agents/$agent.md has model '$(field "$file" model)', models.conf says '$model'"
    [ "$(field "$file" effort)" = "$effort" ] ||
      fail "plugin/agents/$agent.md has effort '$(field "$file" effort)', models.conf says '$effort'"
  else
    write_file "$file" "$model" "$effort" || fail "could not write plugin/agents/$agent.md"
  fi

  generated=$(opencode_file "$agent" "$file" "$omodel" "$ovariant")
  if [ "$check" -eq 1 ]; then
    if [ ! -f "$opencode_agents/$agent.md" ]; then
      fail "opencode/agents/$agent.md is missing"
    elif [ "$generated" != "$(cat "$opencode_agents/$agent.md")" ]; then
      fail "opencode/agents/$agent.md differs from plugin/agents/$agent.md and models.conf"
    fi
  elif ! mkdir -p "$opencode_agents" ||
       ! printf '%s\n' "$generated" > "$opencode_agents/$agent.md"; then
    fail "could not write opencode/agents/$agent.md"
  fi
done < "$conf"

for file in "$agents"/*.md; do
  [ -f "$file" ] || continue
  name=$(basename "$file" .md)
  case $configured in
    *" $name "*) ;;
    *) fail "plugin/agents/$name.md has no line in models.conf" ;;
  esac
done

for file in "$opencode_agents"/*.md; do
  [ -f "$file" ] || continue
  name=$(basename "$file" .md)
  case $configured in
    *" $name "*) ;;
    *) fail "opencode/agents/$name.md has no line in models.conf" ;;
  esac
done

[ "$failures" -eq 0 ] || exit 1
